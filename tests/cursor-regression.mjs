import fs from 'node:fs';
import assert from 'node:assert/strict';
import { gsap } from 'gsap';
const source=fs.readFileSync('src/hooks/usePortfolioMotion.js','utf8');
const start=source.indexOf('    function setupPointer()');
const end=source.indexOf("    $$('a[href",start);
const events=()=>({listeners:{},addEventListener(name,fn){this.listeners[name]=fn;}});
const cursor={x:0,y:0,xPercent:0,yPercent:0,scale:1,autoAlpha:0};
const preview={x:0,y:0,xPercent:0,yPercent:0,scale:.4,rotation:0,autoAlpha:0};
const image={src:''}; const project={...events(),dataset:{preview:"distinct-hover.webp"}};
const document={...events(),documentElement:events()};
const $=(selector)=>({'.cursor':cursor,'.project-preview':preview,'img':image,'.featured-image img':{getAttribute(){return 'project.webp';}}}[selector]);
